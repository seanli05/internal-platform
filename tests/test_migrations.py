"""Migration tests: the scripts in migrations/versions must build exactly the
schema models.py describes, and must run in both directions.

The API tests build their databases with create_all (fast), so without this
file, forgetting to write a migration would go unnoticed until deploy.
"""

from argparse import Namespace

import pytest
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected


@pytest.fixture
def alembic_cfg(tmp_path):
    # Same config the CLI uses, but pointed at a throwaway DB — exactly like
    # `alembic -x db_url=... <command>`.
    return Config("alembic.ini", cmd_opts=Namespace(x=[f"db_url=sqlite:///{tmp_path / 'migrations.db'}"]))


def test_migrations_match_models(alembic_cfg):
    command.upgrade(alembic_cfg, "head")
    try:
        # The same diff autogenerate runs; raises if models.py has changes
        # that no migration covers.
        command.check(alembic_cfg)
    except AutogenerateDiffsDetected as e:
        pytest.fail(f"models.py and migrations disagree — run `alembic revision --autogenerate`.\n{e}")


def test_migrations_downgrade_and_upgrade_again(alembic_cfg):
    command.upgrade(alembic_cfg, "head")
    command.downgrade(alembic_cfg, "base")
    command.upgrade(alembic_cfg, "head")
